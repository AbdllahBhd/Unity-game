"""Build text.js (the game's four-language text table) from the script document.

Reads every Markdown table in Tools/design/yennayer-script.md whose header has an `id`
column and the language columns EN, TQ, FR, AR. Edit the script, then run:

    python3 Tools/design/original/build-text.py

Output: Tools/design/original/text.js defining globalThis.HNText =
    { id: { who, mood, en, tq, fr, ar } }
and the same table for the Unity game, as the data half of HollowNight.Logic.TalesText:
    Assets/Scripts/HollowNight/Logic/TalesText.cs
`who` is jida | girl | boy | children | teryel | "" (narration); `mood` is the word in
brackets after the speaker (telling, teasing, hushed), when present.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "..", "yennayer-script.md")
OUT = os.path.join(HERE, "text.js")
OUT_CS = os.path.join(HERE, "..", "..", "..", "Assets", "Scripts", "HollowNight", "Logic", "TalesText.cs")
SPEAKERS = {"jida": "jida", "girl": "girl", "boy": "boy", "children": "children", "teryel": "teryel"}


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def speaker(raw):
    m = re.match(r"^([A-Za-z]+)\s*(?:\(([^)]*)\))?", raw or "")
    if not m:
        return "", ""
    who = SPEAKERS.get(m.group(1).lower(), "")
    detail = (m.group(2) or "").lower()
    mood = next((w for w in ("telling", "teasing", "hushed") if w in detail), "")
    return who, mood


def write_cs(table):
    # A JSON string literal is also a valid C# string literal (same escapes).
    lit = lambda s: json.dumps(s, ensure_ascii=False)
    rows = "\n".join(
        "            Add({});".format(", ".join(lit(x) for x in (k, v["who"], v["mood"], v["en"], v["tq"], v["fr"], v["ar"])))
        for k, v in table.items()
    )
    with open(OUT_CS, "w", encoding="utf-8") as fh:
        fh.write(
            "// Generated by Tools/design/original/build-text.py from Tools/design/yennayer-script.md.\n"
            "// Do not edit: correct the script, then run the builder again.\n"
            "namespace HollowNight.Logic\n{\n    public static partial class TalesText\n    {\n"
            "        static void Fill()\n        {\n" + rows + "\n        }\n    }\n}\n"
        )


def main():
    with open(SCRIPT, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    table, header = {}, None
    for line in lines:
        if not line.startswith("|"):
            header = None
            continue
        row = cells(line)
        if header is None:
            header = [h.lower() for h in row]
            continue
        if set(row[0]) <= {"-", ":", ""}:
            continue
        if "id" not in header or "en" not in header:
            continue
        if len(row) != len(header):
            sys.exit(f"{row[0]}: {len(row)} cells but the table has {len(header)} columns (a stray '|'?)")
        rec = dict(zip(header, row))
        entry = {lang: rec.get(lang, "") for lang in ("en", "tq", "fr", "ar")}
        entry["who"], entry["mood"] = speaker(rec.get("speaker", ""))
        if rec["id"] in table:
            sys.exit("Duplicate text id: " + rec["id"])
        table[rec["id"]] = entry
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by build-text.py from Tools/design/yennayer-script.md. Do not edit. */\n")
        fh.write("globalThis.HNText = " + json.dumps(table, ensure_ascii=False, indent=1) + ";\n")
    write_cs(table)
    missing = [k for k, v in table.items() if not all(v[l] for l in ("en", "tq", "fr", "ar"))]
    print(f"{len(table)} lines written to text.js")
    if missing:
        sys.exit(f"Missing translations: {missing}")


main()
